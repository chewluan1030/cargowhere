import type { CarparkRecord, HourlyTrendPoint } from '../types/carpark';

function buildHistory(
  capacity: number,
  availableSeries: number[]
): HourlyTrendPoint[] {
  const labels = [
    '02:00',
    '04:00',
    '06:00',
    '08:00',
    '10:00',
    '12:00',
    '14:00',
    '16:00',
    '18:00',
    '20:00',
    '22:00',
    'Now',
  ];
  return labels.map((hourLabel, idx) => {
    const avail = Math.max(
      0,
      Math.min(capacity, availableSeries[idx] ?? availableSeries[0] ?? 0)
    );
    const occupied = capacity - avail;
    const occupancyPct =
      capacity > 0 ? Math.round((occupied / capacity) * 100) : 0;
    return {
      hourLabel,
      availableCars: avail,
      occupancyPct,
    };
  });
}

